"""Power BI exports: ``python -m app.export --out exports/powerbi/``.

Writes tidy CSVs from the warehouse marts and ``reports/results.json`` so the dashboard can be
rebuilt in Power BI, plus a README with suggested visuals and DAX measures. Missing inputs are
reported and skipped; the command never reads ``config/ground_truth.yaml``.
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from pathlib import Path
from typing import Any

import pandas as pd

# Importing the app's data layer outside `streamlit run` logs a "No runtime found" warning per
# cached loader; it is harmless for the CLI, so keep the output clean.
logging.getLogger("streamlit").setLevel(logging.ERROR)

from app import data  # noqa: E402

SEGMENT_COLUMNS = [
    "dimension",
    "value",
    "n_control",
    "n_treatment",
    "control_rate",
    "treatment_rate",
    "abs_lift",
    "ci_low",
    "ci_high",
    "p_value",
    "p_value_adj",
    "significant_adj",
    "recommended_to_ship",
]
GUARDRAIL_COLUMNS = [
    "metric",
    "control",
    "treatment",
    "abs_lift",
    "ci_low",
    "ci_high",
    "p_value",
    "threshold_abs",
    "breached",
]

README = """# Power BI rebuild kit

Generated by `python -m app.export --out exports/powerbi/` (or `make export`). Every file is a
tidy CSV with a header row; rates are fractions (0.345 = 34.5%), money is USD.

| file | grain | source |
|---|---|---|
| `experiment_invoices.csv` | one row per experiment invoice | `fct_experiment_invoices` |
| `summary.csv` | one row per variant | `agg_experiment_summary` |
| `segments.csv` | one row per segment (dimension, value) | `results.json` → `segments` |
| `guardrails.csv` | one row per guardrail metric | `results.json` → `guardrails` |

## Model

Load all four CSVs. Only `experiment_invoices` needs relationships for slicing; the other three
are pre-aggregated and stand alone. Set `failed_at` / `recovered_at` to Date/Time, the `is_*`,
`had_*`, `churned_*`, `significant_adj`, `recommended_to_ship` and `breached` columns to
True/False. Colors: control `#8A8F98`, treatment `#3366CC`.

## DAX measures (on `experiment_invoices`)

```dax
Invoices = COUNTROWS ( experiment_invoices )

Recovered Invoices =
    CALCULATE ( COUNTROWS ( experiment_invoices ), experiment_invoices[is_recovered] = TRUE () )

Recovery Rate = DIVIDE ( [Recovered Invoices], [Invoices] )

Recovery Rate Control =
    CALCULATE ( [Recovery Rate], experiment_invoices[variant] = "control" )

Recovery Rate Treatment =
    CALCULATE ( [Recovery Rate], experiment_invoices[variant] = "treatment" )

Recovery Lift (pp) = ( [Recovery Rate Treatment] - [Recovery Rate Control] ) * 100

Recovery Lift (relative) =
    DIVIDE ( [Recovery Rate Treatment] - [Recovery Rate Control], [Recovery Rate Control] )

Recovered Revenue = SUM ( experiment_invoices[recovered_amount_usd] )

Recovered Revenue per Invoice = DIVIDE ( [Recovered Revenue], [Invoices] )

Billing Ticket Rate =
    DIVIDE (
        CALCULATE ( [Invoices], experiment_invoices[had_billing_ticket_14d] = TRUE () ),
        [Invoices]
    )

Involuntary Churn Rate =
    DIVIDE (
        CALCULATE ( [Invoices], experiment_invoices[churned_involuntary_30d] = TRUE () ),
        [Invoices]
    )
```

The lift measures above are descriptive and respect slicers. Confidence intervals, p-values and
the ship decision are not recomputed in DAX: take them from `segments.csv`, `guardrails.csv`
and the Streamlit Overview page (`results.json`).

## Suggested visuals (mirroring the Streamlit pages)

1. **Overview:** a card per KPI (`Recovery Rate Control`, `Recovery Rate Treatment`,
   `Recovery Lift (pp)`, `Recovered Revenue`), plus a text box with the decision from
   `results.json` → `recommendation`.
2. **Segments:** an error-bar chart (or a scatter with error bars) of `segments.csv`
   `abs_lift` with `ci_low`/`ci_high` on the axis, `dimension` & `value` on the category axis,
   color by `significant_adj`; a slicer on `dimension`; a table with conditional formatting on
   `p_value_adj`; a card filtered to `recommended_to_ship = TRUE`.
3. **Guardrails:** a table of `guardrails.csv` with an icon rule on `breached`; a clustered column
   chart of `Billing Ticket Rate` and `Involuntary Churn Rate` by `variant`.
4. **Explore:** slicers on `country`, `plan_tier`, `card_funding`, `initial_decline_code`; a
   clustered column of `Recovery Rate` by `variant`; a line chart of recovered invoices by
   `hours_to_recovery` (binned to hours, running total as % of `Invoices`); a column chart of
   invoice count by `retries_attempted` and `variant`. Label the page "Descriptive only".
"""


def flatten_segments(results: dict[str, Any]) -> pd.DataFrame:
    """``results.json`` segments as one tidy row per segment, with a ship flag."""
    impact = results.get("revenue_impact") or {}
    ship = {(s.get("dimension"), s.get("value")) for s in impact.get("ship_segments") or []}
    rows = []
    for seg in results.get("segments") or []:
        row = {c: seg.get(c) for c in SEGMENT_COLUMNS if c != "recommended_to_ship"}
        row["recommended_to_ship"] = (seg.get("dimension"), seg.get("value")) in ship
        rows.append(row)
    return pd.DataFrame(rows, columns=SEGMENT_COLUMNS)


def flatten_guardrails(results: dict[str, Any]) -> pd.DataFrame:
    """``results.json`` guardrails as one tidy row per metric."""
    rows = [{c: g.get(c) for c in GUARDRAIL_COLUMNS} for g in results.get("guardrails") or []]
    return pd.DataFrame(rows, columns=GUARDRAIL_COLUMNS)


def _read_results(path: Path) -> dict[str, Any] | None:
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, json.JSONDecodeError):
        return None


def export(out_dir: Path) -> dict[str, int]:
    """Write every export whose input exists. Returns ``{file name: data row count}``."""
    out_dir.mkdir(parents=True, exist_ok=True)
    written: dict[str, int] = {}

    def write(name: str, df: pd.DataFrame) -> None:
        df.to_csv(out_dir / name, index=False, lineterminator="\n")
        written[name] = len(df)

    db = data.input_path("warehouse")
    if db.is_file():
        for name, sql in (
            ("experiment_invoices.csv", data.fact_table_sql()),
            ("summary.csv", data.summary_sql()),
        ):
            df = data.run_query(str(db), sql)
            if df is None:
                print(f"warning: could not read the source of {name} from {db}", file=sys.stderr)
            else:
                write(name, df)
    else:
        print(f"warning: {data.missing_message('warehouse')}", file=sys.stderr)

    results = _read_results(data.input_path("results"))
    if results is None:
        print(f"warning: {data.missing_message('results')}", file=sys.stderr)
    else:
        write("segments.csv", flatten_segments(results))
        write("guardrails.csv", flatten_guardrails(results))

    (out_dir / "README.md").write_text(README, encoding="utf-8")
    return written


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description="Write Power BI CSV exports.")
    parser.add_argument("--out", default="exports/powerbi/", help="output directory")
    args = parser.parse_args(argv)
    out = Path(args.out)
    if not out.is_absolute():
        out = data.project_root() / out
    written = export(out)
    for name, n in written.items():
        print(f"wrote {out / name} ({n:,} rows)")
    print(f"wrote {out / 'README.md'}")
    expected = {"experiment_invoices.csv", "summary.csv", "segments.csv", "guardrails.csv"}
    return 0 if expected <= set(written) else 1


if __name__ == "__main__":
    raise SystemExit(main())
